"use client";

import React, { useState, useMemo, useEffect } from "react";
import {
  FiCalendar,
  FiDownload,
  FiSearch,
  FiFileText,
  FiDollarSign,
  FiPieChart,
  FiTrendingUp,
  FiAlertTriangle,
  FiPackage,
  FiChevronLeft,
  FiChevronRight,
  FiCheckCircle
} from "react-icons/fi";
import {
  ComposedChart,
  Line,
  Bar,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
  ResponsiveContainer,
  Legend,
} from "recharts";

import * as XLSX from "xlsx";

import { API_BASE } from "@/app/lib/api";

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------
function formatINR(n: number) {
  return `₹${n.toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

const PAGE_SIZE = 8;

export default function ReportsPage() {
  const [query, setQuery] = useState("");
  const [dateFilter, setDateFilter] = useState("This Month");
  const [reportType, setReportType] = useState("All");
  const [currentPage, setCurrentPage] = useState(1);

  // API state
  const [summary, setSummary] = useState({ total_sales: 0, total_revenue: 0, total_profit: 0, total_bills: 0 });
  const [revenueData, setRevenueData] = useState<any[]>([]);
  const [topProducts, setTopProducts] = useState<any[]>([]);
  const [lowStock, setLowStock] = useState<any[]>([]);
  const [expiryAlerts, setExpiryAlerts] = useState<any[]>([]);
  const [reportsList, setReportsList] = useState<any[]>([]);

  useEffect(() => {
    fetch(`${API_BASE}/reports/page-data/`)
      .then((res) => res.json())
      .then((data) => {
        setSummary(data.summary || { total_sales: 0, total_revenue: 0, total_profit: 0, total_bills: 0 });
        setRevenueData(data.revenue_data || []);
        setTopProducts(data.top_products || []);
        setLowStock(data.low_stock || []);
        setExpiryAlerts(data.expiry_alerts || []);
        setReportsList(data.reports_list || []);
      })
      .catch((err) => {
        console.error("Failed to load reports data:", err);
      });
  }, []);

  // Filter Table
  // --- helpers ---------------------------------------------------------
  function getDateRange(): { from: string; to: string } | null {
    const today = new Date();
    const fmt = (d: Date) => d.toISOString().split("T")[0];
    if (dateFilter === "Today")     return { from: fmt(today), to: fmt(today) };
    if (dateFilter === "Yesterday") { const y = new Date(today); y.setDate(y.getDate() - 1); return { from: fmt(y), to: fmt(y) }; }
    if (dateFilter === "Last 7 Days") { const f = new Date(today); f.setDate(f.getDate() - 6); return { from: fmt(f), to: fmt(today) }; }
    if (dateFilter === "This Month") { const f = new Date(today.getFullYear(), today.getMonth(), 1); return { from: fmt(f), to: fmt(today) }; }
    if (dateFilter === "Next Month") {
      const firstDayNext = new Date(today.getFullYear(), today.getMonth() + 1, 1);
      const lastDayNext = new Date(today.getFullYear(), today.getMonth() + 2, 0);
      return { from: fmt(firstDayNext), to: fmt(lastDayNext) };
    }
    return null;
  }

  function exportExcel(rows: any[], filename: string) {
    const data = rows.map((r) => ({
      "Report ID": r.id,
      "Date": r.date,
      "Category": r.category,
      "Generated By": r.generatedBy,
      "Status": r.status,
    }));

    const worksheet = XLSX.utils.json_to_sheet(data);
    const workbook = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(workbook, worksheet, "Reports");

    const name = filename.replace(/\.csv$/i, ".xlsx");
    XLSX.writeFile(workbook, name.endsWith(".xlsx") ? name : `${name}.xlsx`);
  }


  // --- filter -----------------------------------------------------------
  const filteredReports = useMemo(() => {
    let filtered = reportsList;
    const range = getDateRange();
    if (range) {
      filtered = filtered.filter((r) => r.date >= range.from && r.date <= range.to);
    }
    if (reportType !== "All") {
      filtered = filtered.filter((r) => r.category === reportType);
    }
    if (query.trim()) {
      const q = query.toLowerCase();
      filtered = filtered.filter(
        (r) => r.id.toLowerCase().includes(q) || r.category.toLowerCase().includes(q)
      );
    }
    return filtered;
  }, [query, reportType, reportsList, dateFilter]);

  const activeSummary = useMemo(() => {
    const range = getDateRange();
    if (!range) return summary;

    const rangeReports = reportsList.filter((r) => r.date >= range.from && r.date <= range.to);

    if (rangeReports.length === 0) {
      if (dateFilter === "This Month" && reportsList.length === 0) {
        return summary;
      }
      return { total_sales: 0, total_revenue: 0, total_profit: 0, total_bills: 0 };
    }

    const total_sales = rangeReports.length;
    const total_revenue = rangeReports.reduce((acc, r) => acc + (Number(r.amount || r.total) || 0), 0) || (dateFilter === "This Month" ? summary.total_revenue : 0);
    const total_profit = rangeReports.reduce((acc, r) => acc + (Number(r.profit) || 0), 0) || (dateFilter === "This Month" ? summary.total_profit : 0);
    const total_bills = rangeReports.length;

    return { total_sales, total_revenue, total_profit, total_bills };
  }, [dateFilter, reportsList, summary]);

  const totalPages = Math.max(1, Math.ceil(filteredReports.length / PAGE_SIZE));
  const paginatedReports = filteredReports.slice((currentPage - 1) * PAGE_SIZE, currentPage * PAGE_SIZE);

  return (
    <div className="min-h-screen p-3 sm:p-5 lg:p-6 bg-slate-50 dark:bg-slate-950 transition-colors">
      <div className="mx-auto max-w-7xl space-y-6 w-full min-w-0">
        
        {/* Header */}
        <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between rounded-2xl border border-slate-200/80 dark:border-slate-800/80 bg-white dark:bg-slate-900 p-5 shadow-sm">
          <div>
            <h1 className="text-2xl font-extrabold tracking-tight text-slate-900 dark:text-white">Advanced Reports</h1>
            <p className="text-xs font-medium text-slate-500 dark:text-slate-400 mt-1">Analyze store performance, inventory alerts, and financial summaries.</p>
          </div>
          
          <div className="flex flex-wrap items-center gap-2.5">
            <div className="flex items-center gap-2 rounded-xl bg-slate-50 dark:bg-slate-800 px-3.5 py-2.5 shadow-sm border border-slate-200/80 dark:border-slate-700/80">
              <FiCalendar size={15} className="text-slate-400" />
              <select 
                className="bg-transparent text-xs font-bold text-slate-800 dark:text-slate-200 outline-none cursor-pointer"
                value={dateFilter}
                onChange={(e) => setDateFilter(e.target.value)}
              >
                <option>Today</option>
                <option>Yesterday</option>
                <option>Last 7 Days</option>
                <option>This Month</option>
                <option>Next Month</option>
              </select>
            </div>
            
            <button 
              onClick={() => exportExcel(filteredReports, `reports-${dateFilter.replace(/ /g,"-")}.xlsx`)}
              className="flex items-center gap-2 rounded-xl bg-emerald-600 px-4 py-2.5 text-xs font-bold text-white shadow-md shadow-emerald-500/20 transition-all hover:bg-emerald-700 active:scale-95">
              <FiDownload size={14} />
              Export Excel
            </button>
          </div>
        </div>

        {/* Summary Cards */}
        <div className="grid grid-cols-2 gap-2.5 sm:gap-4 xl:grid-cols-4">
          <div className="flex flex-col sm:flex-row sm:items-center gap-2 sm:gap-4 rounded-2xl bg-white dark:bg-slate-900 p-3 sm:p-5 shadow-sm border border-slate-200/80 dark:border-slate-800/80 transition hover:shadow-md">
            <div className="flex h-12 w-12 items-center justify-center rounded-2xl bg-blue-50 dark:bg-blue-950/60 text-blue-600 dark:text-blue-400">
              <FiTrendingUp size={22} />
            </div>
            <div>
              <p className="text-[11px] font-bold uppercase tracking-wider text-slate-400 dark:text-slate-500">Total Sales</p>
              <p className="text-xl font-extrabold text-slate-900 dark:text-white mt-0.5">{activeSummary.total_sales.toLocaleString("en-IN")}</p>
            </div>
          </div>

          <div className="flex flex-col sm:flex-row sm:items-center gap-2 sm:gap-4 rounded-2xl bg-white dark:bg-slate-900 p-3 sm:p-5 shadow-sm border border-slate-200/80 dark:border-slate-800/80 transition hover:shadow-md">
            <div className="flex h-12 w-12 items-center justify-center rounded-2xl bg-indigo-50 dark:bg-indigo-950/60 text-indigo-600 dark:text-indigo-400">
              <FiDollarSign size={22} />
            </div>
            <div>
              <p className="text-[11px] font-bold uppercase tracking-wider text-slate-400 dark:text-slate-500">Total Revenue</p>
              <p className="text-xl font-extrabold text-slate-900 dark:text-white mt-0.5">{formatINR(activeSummary.total_revenue)}</p>
            </div>
          </div>

          <div className="flex flex-col sm:flex-row sm:items-center gap-2 sm:gap-4 rounded-2xl bg-white dark:bg-slate-900 p-3 sm:p-5 shadow-sm border border-slate-200/80 dark:border-slate-800/80 transition hover:shadow-md">
            <div className="flex h-12 w-12 items-center justify-center rounded-2xl bg-emerald-50 dark:bg-emerald-950/60 text-emerald-600 dark:text-emerald-400">
              <FiPieChart size={22} />
            </div>
            <div>
              <p className="text-[11px] font-bold uppercase tracking-wider text-slate-400 dark:text-slate-500">Total Profit</p>
              <p className="text-xl font-extrabold text-slate-900 dark:text-white mt-0.5">{formatINR(activeSummary.total_profit)}</p>
            </div>
          </div>

          <div className="flex flex-col sm:flex-row sm:items-center gap-2 sm:gap-4 rounded-2xl bg-white dark:bg-slate-900 p-3 sm:p-5 shadow-sm border border-slate-200/80 dark:border-slate-800/80 transition hover:shadow-md">
            <div className="flex h-12 w-12 items-center justify-center rounded-2xl bg-purple-50 dark:bg-purple-950/60 text-purple-600 dark:text-purple-400">
              <FiFileText size={22} />
            </div>
            <div>
              <p className="text-[11px] font-bold uppercase tracking-wider text-slate-400 dark:text-slate-500">Total Bills</p>
              <p className="text-xl font-extrabold text-slate-900 dark:text-white mt-0.5">{activeSummary.total_bills.toLocaleString("en-IN")}</p>
            </div>
          </div>
        </div>

        {/* Main Analytics Chart Row */}
        <div className="rounded-2xl bg-white dark:bg-slate-900 p-6 shadow-sm border border-slate-200/80 dark:border-slate-800/80">
          <div className="flex items-center justify-between mb-4">
            <div>
              <h3 className="text-sm font-bold text-slate-900 dark:text-white">Revenue vs Profit Analysis</h3>
              <p className="text-xs text-slate-500 dark:text-slate-400">Visual comparison of total earnings and net margins over time.</p>
            </div>
          </div>
          <div className="h-72 w-full min-w-0 pt-2">
            <ResponsiveContainer width="100%" height="100%">
              <ComposedChart data={revenueData} margin={{ top: 10, right: 15, left: -5, bottom: 0 }}>
                <CartesianGrid strokeDasharray="3 3" vertical={false} stroke="#E2E8F0" />
                <XAxis dataKey="name" axisLine={false} tickLine={false} tick={{ fill: '#64748B', fontSize: 12, fontWeight: 600 }} dy={10} />
                <YAxis 
                  axisLine={false} 
                  tickLine={false} 
                  width={65}
                  tick={{ fill: '#64748B', fontSize: 11, fontWeight: 500 }} 
                  tickFormatter={(val) => {
                    const n = Number(val) || 0;
                    if (n >= 100000) return `₹${(n / 100000).toFixed(1)}L`;
                    if (n >= 1000) return `₹${Math.round(n / 1000)}k`;
                    return `₹${n}`;
                  }} 
                />
                <Tooltip 
                  contentStyle={{ borderRadius: '16px', border: '1px solid #e2e8f0', boxShadow: '0 10px 25px -5px rgba(0,0,0,0.1)', padding: '12px 16px' }}
                  formatter={(value) => formatINR(Number(value) || 0)}
                />
                <Legend iconType="circle" wrapperStyle={{ paddingTop: '20px', fontSize: '12px', fontWeight: 600 }} />
                <Bar dataKey="revenue" name="Revenue" fill="#2563EB" radius={[6, 6, 0, 0]} barSize={36} />
                <Line type="monotone" dataKey="profit" name="Profit" stroke="#10B981" strokeWidth={3.5} dot={{ r: 4, strokeWidth: 2, fill: '#fff' }} activeDot={{ r: 6 }} />
              </ComposedChart>
            </ResponsiveContainer>
          </div>
        </div>

        {/* Mini Reports Grid with Equal Heights & Clean Empty States */}
        <div className="grid grid-cols-1 gap-5 lg:grid-cols-3">
          
          {/* Top Products */}
          <div className="flex flex-col h-full rounded-2xl bg-white dark:bg-slate-900 shadow-sm border border-slate-200/80 dark:border-slate-800/80 overflow-hidden">
            <div className="p-4 border-b border-slate-100 dark:border-slate-800/80 bg-slate-50/50 dark:bg-slate-900/50 flex items-center justify-between">
              <div className="flex items-center gap-2">
                <FiTrendingUp className="text-blue-600" size={16} />
                <h3 className="font-bold text-slate-900 dark:text-white text-xs">Most Profitable Items</h3>
              </div>
              <span className="text-[10px] font-bold text-blue-600 bg-blue-50 dark:bg-blue-950/60 dark:text-blue-400 px-2 py-0.5 rounded-md">Top Sales</span>
            </div>
            <div className="p-4 flex-1 flex flex-col justify-center space-y-3">
              {topProducts.length > 0 ? (
                topProducts.map((p, i) => (
                  <div key={p.id || i} className="flex items-center justify-between border-b border-slate-50 dark:border-slate-800/50 pb-2.5 last:border-b-0 last:pb-0">
                    <div className="flex items-center gap-3 overflow-hidden">
                      <div className="flex h-6 w-6 shrink-0 items-center justify-center rounded-lg bg-blue-50 dark:bg-blue-950/60 text-[10px] font-extrabold text-blue-600 dark:text-blue-400">
                        #{i + 1}
                      </div>
                      <p className="text-xs font-bold text-slate-800 dark:text-slate-100 truncate">{p.name}</p>
                    </div>
                    <span className="text-xs font-bold text-slate-900 dark:text-white tabular-nums shrink-0">{formatINR(p.profit)}</span>
                  </div>
                ))
              ) : (
                <div className="py-8 text-center">
                  <p className="text-xs font-semibold text-slate-400">No Sales Data Available</p>
                </div>
              )}
            </div>
          </div>

          {/* Low Stock Alerts */}
          <div className="flex flex-col h-full rounded-2xl bg-white dark:bg-slate-900 shadow-sm border border-slate-200/80 dark:border-slate-800/80 overflow-hidden">
            <div className="p-4 border-b border-slate-100 dark:border-slate-800/80 bg-slate-50/50 dark:bg-slate-900/50 flex items-center justify-between">
              <div className="flex items-center gap-2">
                <FiPackage className="text-amber-600" size={16} />
                <h3 className="font-bold text-slate-900 dark:text-white text-xs">Low Stock Alerts</h3>
              </div>
              <span className="text-[10px] font-bold text-amber-600 bg-amber-50 dark:bg-amber-950/60 dark:text-amber-400 px-2 py-0.5 rounded-md">Action Needed</span>
            </div>
            <div className="p-4 flex-1 flex flex-col justify-center space-y-3">
              {lowStock.length > 0 ? (
                lowStock.map((p, i) => (
                  <div key={p.id || i} className="flex items-center justify-between border-b border-slate-50 dark:border-slate-800/50 pb-2.5 last:border-b-0 last:pb-0">
                    <p className="text-xs font-bold text-slate-800 dark:text-slate-100 truncate pr-2">{p.name}</p>
                    <span className="inline-flex items-center rounded-lg px-2 py-0.5 text-[11px] font-bold text-amber-700 dark:text-amber-300 bg-amber-50 dark:bg-amber-950/60 border border-amber-200/60 dark:border-amber-800/60 shrink-0">
                      {p.stock} left
                    </span>
                  </div>
                ))
              ) : (
                <div className="py-8 text-center">
                  <p className="text-xs font-bold text-emerald-600 dark:text-emerald-400">All Items Well Stocked</p>
                  <p className="text-[11px] text-slate-400 mt-0.5">No low inventory warnings.</p>
                </div>
              )}
            </div>
          </div>

          {/* Expiry Alerts */}
          <div className="flex flex-col h-full rounded-2xl bg-white dark:bg-slate-900 shadow-sm border border-slate-200/80 dark:border-slate-800/80 overflow-hidden">
            <div className="p-4 border-b border-slate-100 dark:border-slate-800/80 bg-slate-50/50 dark:bg-slate-900/50 flex items-center justify-between">
              <div className="flex items-center gap-2">
                <FiAlertTriangle className="text-red-600" size={16} />
                <h3 className="font-bold text-slate-900 dark:text-white text-xs">Expiry Alerts</h3>
              </div>
              <span className="text-[10px] font-bold text-red-600 bg-red-50 dark:bg-red-950/60 dark:text-red-400 px-2 py-0.5 rounded-md">Spoilage Risk</span>
            </div>
            <div className="p-4 flex-1 flex flex-col justify-center space-y-3">
              {expiryAlerts.length > 0 ? (
                expiryAlerts.map((p, i) => (
                  <div key={p.id || i} className="flex items-center justify-between border-b border-slate-50 dark:border-slate-800/50 pb-2.5 last:border-b-0 last:pb-0">
                    <p className="text-xs font-bold text-slate-800 dark:text-slate-100 truncate pr-2">{p.name}</p>
                    <span className={`inline-flex items-center rounded-lg px-2 py-0.5 text-[11px] font-bold shrink-0 ${
                      p.days === 0 
                        ? 'bg-red-50 text-red-700 dark:bg-red-950/60 dark:text-red-400 border border-red-200/60' 
                        : 'bg-amber-50 text-amber-700 dark:bg-amber-950/60 dark:text-amber-400 border border-amber-200/60'
                    }`}>
                      {p.days === 0 ? 'Expires Today' : `in ${p.days} days`}
                    </span>
                  </div>
                ))
              ) : (
                <div className="py-6 text-center flex flex-col items-center">
                  <div className="h-8 w-8 rounded-full bg-emerald-50 dark:bg-emerald-950/60 text-emerald-600 dark:text-emerald-400 flex items-center justify-center mb-1.5">
                    <FiCheckCircle size={18} />
                  </div>
                  <p className="text-xs font-bold text-slate-800 dark:text-slate-200">No Expiry Alerts</p>
                  <p className="text-[11px] text-slate-400 mt-0.5">All products are well within shelf life.</p>
                </div>
              )}
            </div>
          </div>

        </div>

        {/* Reports Table Section */}
        <div className="rounded-2xl bg-white dark:bg-slate-900 shadow-sm border border-slate-200/80 dark:border-slate-800/80 overflow-hidden flex flex-col">

          <div className="flex flex-col sm:flex-row items-center justify-between gap-3 p-4 border-b border-slate-100 dark:border-slate-800 bg-slate-50 dark:bg-slate-800/50">
            <div className="flex items-center gap-3 w-full sm:w-auto">
              <select 
                className="rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 px-3 py-1.5 text-xs font-semibold text-slate-700 dark:text-slate-200 outline-none focus:border-blue-400 focus:ring-2 focus:ring-blue-100 w-full sm:w-auto"
                value={reportType}
                onChange={(e) => { setReportType(e.target.value); setCurrentPage(1); }}
              >
                <option value="All">All Reports</option>
                <option value="Sales">Sales Reports</option>
                <option value="Inventory">Inventory Reports</option>
                <option value="Taxes">Tax Reports</option>
                <option value="Expenses">Expense Reports</option>
              </select>
            </div>

            <div className="relative w-full sm:w-64">
              <FiSearch className="absolute left-3 top-1/2 -translate-y-1/2 text-slate-400" size={14} />
              <input 
                type="text" 
                value={query}
                onChange={(e) => { setQuery(e.target.value); setCurrentPage(1); }}
                placeholder="Search report ID..." 
                className="w-full rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 py-1.5 pl-8 pr-3 text-xs outline-none transition focus:border-blue-400 focus:ring-2 focus:ring-blue-100"
              />
            </div>
          </div>

          <div className="flex-1 crm-table-container">
            <table className="w-full min-w-[700px] text-left border-collapse">
              <thead>
                <tr className="bg-slate-50 dark:bg-slate-800/70 border-b border-slate-100 dark:border-slate-800 text-[10px] uppercase tracking-widest text-slate-400">
                  <th className="px-4 py-2 font-bold">Report ID</th>
                  <th className="px-4 py-2 font-bold">Date</th>
                  <th className="px-4 py-2 font-bold">Category</th>
                  <th className="px-4 py-2 font-bold">Generated By</th>
                  <th className="px-4 py-2 font-bold">Status</th>
                  <th className="px-4 py-2 font-bold text-center">Action</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-50 text-[12px]">
                {paginatedReports.length > 0 ? paginatedReports.map((report) => (
                  <tr key={report.id} className="transition-colors hover:bg-slate-50 dark:bg-slate-800/70">
                    <td className="px-4 py-2.5 font-semibold text-blue-600">{report.id}</td>
                    <td className="px-4 py-2.5 text-slate-600 dark:text-slate-300 font-medium">{report.date}</td>
                    <td className="px-4 py-2.5 text-slate-600 dark:text-slate-300 font-semibold">{report.category}</td>
                    <td className="px-4 py-2.5 text-slate-600 dark:text-slate-300">{report.generatedBy}</td>
                    <td className="px-4 py-2.5">
                      <span className={`inline-flex rounded-full px-2 py-0.5 text-[10px] uppercase tracking-wider font-bold ${
                        report.status === 'Ready' ? 'bg-green-100 text-green-700' : 'bg-red-100 text-red-700'
                      }`}>
                        {report.status}
                      </span>
                    </td>
                    <td className="px-4 py-2.5">
                       <div className="flex items-center justify-center gap-1.5">
                          <button 
                            onClick={() => exportExcel([report], `${report.id}.xlsx`)}
                            className="flex h-7 w-7 items-center justify-center rounded bg-slate-100 dark:bg-slate-800 text-slate-500 dark:text-slate-400 transition hover:bg-emerald-100 hover:text-emerald-600 dark:hover:bg-emerald-950 dark:hover:text-emerald-400" 
                            title="Download Excel (.xlsx)">
                            <FiDownload size={12} />
                          </button>
                       </div>
                    </td>
                  </tr>
                )) : (
                  <tr>
                    <td colSpan={6} className="px-6 py-12 text-center text-slate-500 dark:text-slate-400">
                      No reports found for the selected criteria.
                    </td>
                  </tr>
                )}
              </tbody>
            </table>
          </div>

          {/* Pagination */}
          {totalPages > 1 && (
            <div className="flex items-center justify-between border-t border-slate-100 dark:border-slate-800 px-4 py-3 bg-white dark:bg-slate-900">
              <span className="text-[11px] font-medium text-slate-500 dark:text-slate-400">
                Page <span className="font-bold text-slate-800 dark:text-white">{currentPage}</span> of {totalPages}
              </span>
              <div className="flex items-center gap-1.5">
                <button 
                  onClick={() => setCurrentPage(p => Math.max(1, p - 1))}
                  disabled={currentPage === 1}
                  className="flex h-7 w-7 items-center justify-center rounded-lg border border-slate-200 dark:border-slate-700 text-slate-500 dark:text-slate-400 hover:bg-slate-50 dark:bg-slate-800 disabled:opacity-50"
                >
                  <FiChevronLeft size={14} />
                </button>
                <button 
                  onClick={() => setCurrentPage(p => Math.min(totalPages, p + 1))}
                  disabled={currentPage === totalPages}
                  className="flex h-7 w-7 items-center justify-center rounded-lg border border-slate-200 dark:border-slate-700 text-slate-500 dark:text-slate-400 hover:bg-slate-50 dark:bg-slate-800 disabled:opacity-50"
                >
                  <FiChevronRight size={14} />
                </button>
              </div>
            </div>
          )}
        </div>

      </div>
    </div>
  );
}
