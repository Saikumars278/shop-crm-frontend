"use client";

import React, { useState, useMemo, useEffect } from "react";
import {
  FiCalendar,
  FiDownload,
  FiSearch,
  FiFileText,
  FiDollarSign,
  FiPieChart,
  FiTrendingUp,
  FiAlertTriangle,
  FiClock,
  FiPackage,
  FiChevronLeft,
  FiChevronRight
} from "react-icons/fi";
import {
  ComposedChart,
  Line,
  Bar,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
  ResponsiveContainer,
  Legend,
} from "recharts";

const API_BASE = process.env.NEXT_PUBLIC_API_URL || "http://127.0.0.1:8000/api";

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------
function formatINR(n: number) {
  return `₹${n.toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

const PAGE_SIZE = 8;

export default function ReportsPage() {
  const [query, setQuery] = useState("");
  const [dateFilter, setDateFilter] = useState("This Month");
  const [reportType, setReportType] = useState("All");
  const [currentPage, setCurrentPage] = useState(1);

  // API state
  const [summary, setSummary] = useState({ total_sales: 0, total_revenue: 0, total_profit: 0, total_bills: 0 });
  const [revenueData, setRevenueData] = useState<any[]>([]);
  const [topProducts, setTopProducts] = useState<any[]>([]);
  const [lowStock, setLowStock] = useState<any[]>([]);
  const [expiryAlerts, setExpiryAlerts] = useState<any[]>([]);
  const [reportsList, setReportsList] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    fetch(`${API_BASE}/reports/page-data/`)
      .then((res) => res.json())
      .then((data) => {
        setSummary(data.summary || { total_sales: 0, total_revenue: 0, total_profit: 0, total_bills: 0 });
        setRevenueData(data.revenue_data || []);
        setTopProducts(data.top_products || []);
        setLowStock(data.low_stock || []);
        setExpiryAlerts(data.expiry_alerts || []);
        setReportsList(data.reports_list || []);
        setLoading(false);
      })
      .catch((err) => {
        console.error("Failed to load reports data:", err);
        setLoading(false);
      });
  }, []);

  // Filter Table
  // --- helpers ---------------------------------------------------------
  function getDateRange(): { from: string; to: string } | null {
    const today = new Date();
    const fmt = (d: Date) => d.toISOString().split("T")[0];
    if (dateFilter === "Today")     return { from: fmt(today), to: fmt(today) };
    if (dateFilter === "Yesterday") { const y = new Date(today); y.setDate(y.getDate() - 1); return { from: fmt(y), to: fmt(y) }; }
    if (dateFilter === "Last 7 Days") { const f = new Date(today); f.setDate(f.getDate() - 6); return { from: fmt(f), to: fmt(today) }; }
    if (dateFilter === "This Month") { const f = new Date(today.getFullYear(), today.getMonth(), 1); return { from: fmt(f), to: fmt(today) }; }
    return null;
  }

  function exportCSV(rows: any[], filename: string) {
    const headers = ["Report ID", "Date", "Category", "Generated By", "Status"];
    const lines = [
      headers.join(","),
      ...rows.map(r => [r.id, r.date, r.category, r.generatedBy, r.status].join(","))
    ];
    const blob = new Blob([lines.join("\n")], { type: "text/csv" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a"); a.href = url; a.download = filename; a.click();
    URL.revokeObjectURL(url);
  }

  function printTable(rows: any[]) {
    const w = window.open("", "", "width=900,height=700");
    if (!w) return;
    w.document.write(`
      <html><head><title>Reports</title>
      <style>body{font-family:sans-serif;padding:24px;color:#333}table{width:100%;border-collapse:collapse;font-size:13px}th{background:#f1f5f9;padding:8px 12px;text-align:left;font-size:11px;text-transform:uppercase;color:#64748b}td{padding:8px 12px;border-bottom:1px solid #f1f5f9}.badge-ready{color:#15803d;background:#dcfce7;padding:2px 8px;border-radius:999px;font-size:10px;font-weight:700}.badge-pending{color:#b45309;background:#fef3c7;padding:2px 8px;border-radius:999px;font-size:10px;font-weight:700}</style>
      </head><body>
      <h2 style="margin-bottom:16px">Reports — ${dateFilter}</h2>
      <table><thead><tr><th>Report ID</th><th>Date</th><th>Category</th><th>Generated By</th><th>Status</th></tr></thead>
      <tbody>${rows.map(r => `<tr><td>${r.id}</td><td>${r.date}</td><td>${r.category}</td><td>${r.generatedBy}</td><td><span class="badge-${r.status === 'Ready' ? 'ready' : 'pending'}">${r.status}</span></td></tr>`).join("")}</tbody>
      </table></body></html>`);
    w.document.close(); w.focus(); w.print(); w.close();
  }

  // --- filter -----------------------------------------------------------
  const filteredReports = useMemo(() => {
    let filtered = reportsList;
    const range = getDateRange();
    if (range) {
      filtered = filtered.filter((r) => r.date >= range.from && r.date <= range.to);
    }
    if (reportType !== "All") {
      filtered = filtered.filter((r) => r.category === reportType);
    }
    if (query.trim()) {
      const q = query.toLowerCase();
      filtered = filtered.filter(
        (r) => r.id.toLowerCase().includes(q) || r.category.toLowerCase().includes(q)
      );
    }
    return filtered;
  }, [query, reportType, reportsList, dateFilter]);

  const totalPages = Math.max(1, Math.ceil(filteredReports.length / PAGE_SIZE));
  const paginatedReports = filteredReports.slice((currentPage - 1) * PAGE_SIZE, currentPage * PAGE_SIZE);

  return (
    <div className="min-h-screen p-5 bg-gradient-to-br from-slate-50 to-white dark:from-slate-950 dark:to-slate-900">
      <div className="mx-auto w-full space-y-4">
        
        {/* Header */}
        <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
          <div>
            <h1 className="text-2xl font-bold tracking-tight text-slate-800 dark:text-white">Advanced Reports</h1>
            <p className="text-sm text-slate-500 dark:text-slate-400 mt-1">Analyze performance, inventory alerts, and financial summaries.</p>
          </div>
          
          <div className="flex flex-wrap items-center gap-2">
            <div className="flex items-center gap-2 rounded-xl bg-white dark:bg-slate-900 px-3 py-2 shadow-sm border border-slate-200 dark:border-slate-700">
              <FiCalendar size={14} className="text-slate-400" />
              <select 
                className="bg-transparent text-sm font-semibold text-slate-700 dark:text-slate-200 outline-none cursor-pointer"
                value={dateFilter}
                onChange={(e) => setDateFilter(e.target.value)}
              >
                <option>Today</option>
                <option>Yesterday</option>
                <option>Last 7 Days</option>
                <option>This Month</option>
              </select>
            </div>
            
            <button 
              onClick={() => exportCSV(filteredReports, `reports-${dateFilter.replace(/ /g,"-")}.csv`)}
              className="flex items-center gap-1.5 rounded-xl bg-green-600 px-3 py-2 text-xs font-bold text-white shadow-sm transition-all hover:bg-green-700 active:scale-95">
              <FiDownload size={14} />
              Excel
            </button>
            <button 
              onClick={() => printTable(filteredReports)}
              className="flex items-center gap-1.5 rounded-xl bg-red-600 px-3 py-2 text-xs font-bold text-white shadow-sm transition-all hover:bg-red-700 active:scale-95">
              <FiFileText size={14} />
              PDF
            </button>
          </div>
        </div>

        {/* Summary Cards */}
        <div className="grid grid-cols-1 gap-3 sm:grid-cols-2 xl:grid-cols-4">
          <div className="flex items-center gap-3 rounded-2xl bg-white dark:bg-slate-900 p-4 shadow-sm border border-slate-100 dark:border-slate-800 transition hover:shadow-md">
            <div className="rounded-xl bg-blue-50 p-2.5">
              <FiTrendingUp className="text-lg text-blue-600" />
            </div>
            <div>
              <p className="text-[11px] font-semibold uppercase tracking-wider text-slate-500 dark:text-slate-400">Total Sales</p>
              <p className="text-xl font-bold text-slate-800 dark:text-white">{summary.total_sales.toLocaleString("en-IN")}</p>
            </div>
          </div>
          <div className="flex items-center gap-3 rounded-2xl bg-white dark:bg-slate-900 p-4 shadow-sm border border-slate-100 dark:border-slate-800 transition hover:shadow-md">
            <div className="rounded-xl bg-indigo-50 p-2.5">
              <FiDollarSign className="text-lg text-indigo-600" />
            </div>
            <div>
              <p className="text-[11px] font-semibold uppercase tracking-wider text-slate-500 dark:text-slate-400">Total Revenue</p>
              <p className="text-xl font-bold text-slate-800 dark:text-white">{formatINR(summary.total_revenue)}</p>
            </div>
          </div>
          <div className="flex items-center gap-3 rounded-2xl bg-white dark:bg-slate-900 p-4 shadow-sm border border-slate-100 dark:border-slate-800 transition hover:shadow-md">
            <div className="rounded-xl bg-green-50 p-2.5">
              <FiPieChart className="text-lg text-green-600" />
            </div>
            <div>
              <p className="text-[11px] font-semibold uppercase tracking-wider text-slate-500 dark:text-slate-400">Total Profit</p>
              <p className="text-xl font-bold text-slate-800 dark:text-white">{formatINR(summary.total_profit)}</p>
            </div>
          </div>
          <div className="flex items-center gap-3 rounded-2xl bg-white dark:bg-slate-900 p-4 shadow-sm border border-slate-100 dark:border-slate-800 transition hover:shadow-md">
            <div className="rounded-xl bg-purple-50 p-2.5">
              <FiFileText className="text-lg text-purple-600" />
            </div>
            <div>
              <p className="text-[11px] font-semibold uppercase tracking-wider text-slate-500 dark:text-slate-400">Total Bills</p>
              <p className="text-xl font-bold text-slate-800 dark:text-white">{summary.total_bills.toLocaleString("en-IN")}</p>
            </div>
          </div>
        </div>

        {/* Main Analytics Row */}
        <div className="rounded-2xl bg-white dark:bg-slate-900 p-4 shadow-sm border border-slate-100 dark:border-slate-800">
          <h3 className="text-sm font-bold text-slate-800 dark:text-white mb-4">Revenue vs Profit Analysis</h3>
          <div className="h-64 w-full">
            <ResponsiveContainer width="100%" height="100%">
              <ComposedChart data={revenueData} margin={{ top: 10, right: 10, left: 0, bottom: 0 }}>
                <CartesianGrid strokeDasharray="3 3" vertical={false} stroke="#E3E6EA" />
                <XAxis dataKey="name" axisLine={false} tickLine={false} tick={{ fill: '#9AA3AF', fontSize: 12 }} dy={10} />
                <YAxis axisLine={false} tickLine={false} tick={{ fill: '#9AA3AF', fontSize: 12 }} tickFormatter={(val) => `₹${val/1000}k`} dx={-10} />
                <Tooltip 
                  contentStyle={{ borderRadius: '12px', border: 'none', boxShadow: '0 10px 25px -5px rgba(0,0,0,0.1)' }}
                  formatter={(value) => formatINR(Number(value) || 0)}
                />
                <Legend iconType="circle" wrapperStyle={{ paddingTop: '20px' }} />
                <Bar dataKey="revenue" name="Revenue" fill="#215CF6" radius={[4, 4, 0, 0]} barSize={40} />
                <Line type="monotone" dataKey="profit" name="Profit" stroke="#10B981" strokeWidth={4} dot={{ r: 4, strokeWidth: 2 }} />
              </ComposedChart>
            </ResponsiveContainer>
          </div>
        </div>

        {/* Mini Reports Grid */}
        <div className="grid grid-cols-1 gap-4 lg:grid-cols-3">
          
          {/* Top Products */}
          <div className="flex flex-col rounded-2xl bg-white dark:bg-slate-900 shadow-sm border border-slate-100 dark:border-slate-800 overflow-hidden">
            <div className="p-4 border-b border-slate-100 dark:border-slate-800 bg-slate-50 dark:bg-slate-800/50 flex items-center gap-2">
              <FiTrendingUp className="text-blue-600" size={14} />
              <h3 className="font-bold text-slate-800 dark:text-white text-sm">Most Profitable</h3>
            </div>
            <div className="p-3 space-y-3">
              {topProducts.map((p, i) => (
                <div key={p.id} className="flex items-center justify-between">
                  <div className="flex items-center gap-2.5">
                    <div className="flex h-6 w-6 items-center justify-center rounded-md bg-blue-50 text-[10px] font-bold text-blue-600">#{i + 1}</div>
                    <p className="text-[12px] font-semibold text-slate-800 dark:text-white line-clamp-1">{p.name}</p>
                  </div>
                  <span className="text-[12px] font-bold text-slate-800 dark:text-white tabular-nums">{formatINR(p.profit)}</span>
                </div>
              ))}
            </div>
          </div>

          {/* Low Stock Alerts */}
          <div className="flex flex-col rounded-2xl bg-white dark:bg-slate-900 shadow-sm border border-slate-100 dark:border-slate-800 overflow-hidden">
            <div className="p-4 border-b border-slate-100 dark:border-slate-800 bg-slate-50 dark:bg-slate-800/50 flex items-center gap-2">
              <FiPackage className="text-orange-600" size={14} />
              <h3 className="font-bold text-slate-800 dark:text-white text-sm">Low Stock Alerts</h3>
            </div>
            <div className="p-3 space-y-3">
              {lowStock.map((p) => (
                <div key={p.id} className="flex items-center justify-between">
                  <p className="text-[12px] font-semibold text-slate-800 dark:text-white line-clamp-1">{p.name}</p>
                  <span className="inline-flex rounded px-1.5 py-0.5 text-[10px] font-bold text-orange-700 bg-orange-100">
                    {p.stock} left
                  </span>
                </div>
              ))}
            </div>
          </div>

          {/* Expiry Alerts */}
          <div className="flex flex-col rounded-2xl bg-white dark:bg-slate-900 shadow-sm border border-slate-100 dark:border-slate-800 overflow-hidden">
            <div className="p-4 border-b border-slate-100 dark:border-slate-800 bg-slate-50 dark:bg-slate-800/50 flex items-center gap-2">
              <FiAlertTriangle className="text-red-600" size={14} />
              <h3 className="font-bold text-slate-800 dark:text-white text-sm">Expiry Alerts</h3>
            </div>
            <div className="p-3 space-y-3">
              {expiryAlerts.map((p) => (
                <div key={p.id} className="flex items-center justify-between">
                  <p className="text-[12px] font-semibold text-slate-800 dark:text-white line-clamp-1">{p.name}</p>
                  <span className={`inline-flex rounded px-1.5 py-0.5 text-[10px] font-bold ${
                    p.days === 0 ? 'bg-red-100 text-red-700' : 'bg-orange-100 text-orange-700'
                  }`}>
                    {p.days === 0 ? 'Expires Today' : `in ${p.days} days`}
                  </span>
                </div>
              ))}
            </div>
          </div>

        </div>

        {/* Reports Table Section */}
        <div className="rounded-2xl bg-white dark:bg-slate-900 shadow-sm border border-slate-100 dark:border-slate-800 overflow-hidden flex flex-col mt-4">
          <div className="flex flex-col sm:flex-row items-center justify-between gap-3 p-4 border-b border-slate-100 dark:border-slate-800 bg-slate-50 dark:bg-slate-800/50">
            <div className="flex items-center gap-3 w-full sm:w-auto">
              <select 
                className="rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 px-3 py-1.5 text-xs font-semibold text-slate-700 dark:text-slate-200 outline-none focus:border-blue-400 focus:ring-2 focus:ring-blue-100 w-full sm:w-auto"
                value={reportType}
                onChange={(e) => { setReportType(e.target.value); setCurrentPage(1); }}
              >
                <option value="All">All Reports</option>
                <option value="Sales">Sales Reports</option>
                <option value="Inventory">Inventory Reports</option>
                <option value="Taxes">Tax Reports</option>
                <option value="Expenses">Expense Reports</option>
              </select>
            </div>

            <div className="relative w-full sm:w-64">
              <FiSearch className="absolute left-3 top-1/2 -translate-y-1/2 text-slate-400" size={14} />
              <input 
                type="text" 
                value={query}
                onChange={(e) => { setQuery(e.target.value); setCurrentPage(1); }}
                placeholder="Search report ID..." 
                className="w-full rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 py-1.5 pl-8 pr-3 text-xs outline-none transition focus:border-blue-400 focus:ring-2 focus:ring-blue-100"
              />
            </div>
          </div>

          <div className="flex-1 overflow-x-auto">
            <table className="w-full min-w-[700px] text-left border-collapse">
              <thead>
                <tr className="bg-slate-50 dark:bg-slate-800/70 border-b border-slate-100 dark:border-slate-800 text-[10px] uppercase tracking-widest text-slate-400">
                  <th className="px-4 py-2 font-bold">Report ID</th>
                  <th className="px-4 py-2 font-bold">Date</th>
                  <th className="px-4 py-2 font-bold">Category</th>
                  <th className="px-4 py-2 font-bold">Generated By</th>
                  <th className="px-4 py-2 font-bold">Status</th>
                  <th className="px-4 py-2 font-bold text-center">Action</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-50 text-[12px]">
                {paginatedReports.length > 0 ? paginatedReports.map((report) => (
                  <tr key={report.id} className="transition-colors hover:bg-slate-50 dark:bg-slate-800/70">
                    <td className="px-4 py-2.5 font-semibold text-blue-600">{report.id}</td>
                    <td className="px-4 py-2.5 text-slate-600 dark:text-slate-300 font-medium">{report.date}</td>
                    <td className="px-4 py-2.5 text-slate-600 dark:text-slate-300 font-semibold">{report.category}</td>
                    <td className="px-4 py-2.5 text-slate-600 dark:text-slate-300">{report.generatedBy}</td>
                    <td className="px-4 py-2.5">
                      <span className={`inline-flex rounded-full px-2 py-0.5 text-[10px] uppercase tracking-wider font-bold ${
                        report.status === 'Ready' ? 'bg-green-100 text-green-700' : 'bg-red-100 text-red-700'
                      }`}>
                        {report.status}
                      </span>
                    </td>
                    <td className="px-4 py-2.5">
                       <div className="flex items-center justify-center gap-1.5">
                          <button 
                            onClick={() => exportCSV([report], `${report.id}.csv`)}
                            className="flex h-7 w-7 items-center justify-center rounded bg-slate-100 text-slate-500 dark:text-slate-400 transition hover:bg-blue-100 hover:text-blue-600" 
                            title="Download CSV">
                            <FiDownload size={12} />
                          </button>
                       </div>
                    </td>
                  </tr>
                )) : (
                  <tr>
                    <td colSpan={6} className="px-6 py-12 text-center text-slate-500 dark:text-slate-400">
                      No reports found for the selected criteria.
                    </td>
                  </tr>
                )}
              </tbody>
            </table>
          </div>

          {/* Pagination */}
          {totalPages > 1 && (
            <div className="flex items-center justify-between border-t border-slate-100 dark:border-slate-800 px-4 py-3 bg-white dark:bg-slate-900">
              <span className="text-[11px] font-medium text-slate-500 dark:text-slate-400">
                Page <span className="font-bold text-slate-800 dark:text-white">{currentPage}</span> of {totalPages}
              </span>
              <div className="flex items-center gap-1.5">
                <button 
                  onClick={() => setCurrentPage(p => Math.max(1, p - 1))}
                  disabled={currentPage === 1}
                  className="flex h-7 w-7 items-center justify-center rounded-lg border border-slate-200 dark:border-slate-700 text-slate-500 dark:text-slate-400 hover:bg-slate-50 dark:bg-slate-800 disabled:opacity-50"
                >
                  <FiChevronLeft size={14} />
                </button>
                <button 
                  onClick={() => setCurrentPage(p => Math.min(totalPages, p + 1))}
                  disabled={currentPage === totalPages}
                  className="flex h-7 w-7 items-center justify-center rounded-lg border border-slate-200 dark:border-slate-700 text-slate-500 dark:text-slate-400 hover:bg-slate-50 dark:bg-slate-800 disabled:opacity-50"
                >
                  <FiChevronRight size={14} />
                </button>
              </div>
            </div>
          )}
        </div>

      </div>
    </div>
  );
}
